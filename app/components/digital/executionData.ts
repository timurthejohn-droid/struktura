export const EX_STARTS = [0, 0.2, 0.4, 0.6, 0.8];
/** Кадр, в котором сцена «досказана», — для навигации и режима без анимации. */
export const EX_KEYFRAMES = [0.15, 0.35, 0.55, 0.75, 1];

export function exStepAt(p: number) {
  let s = 0;
  for (let i = 0; i < EX_STARTS.length; i++) if (p >= EX_STARTS[i]) s = i;
  return s;
}

/** Локальный прогресс внутри сцены (последняя сцена заканчивается чуть раньше конца секции). */
export function exLocal(p: number, step: number) {
  const len = step === EX_STARTS.length - 1 ? 0.17 : EX_STARTS[step + 1] - EX_STARTS[step];
  return Math.max(0, Math.min(1, (p - EX_STARTS[step]) / len));
}
