// Границы сцен — как в эскизе (0 / 125 / 250 / 375 / 475 / 575 / 675 / 775 / 900 из 1000).
export const CORE_STARTS = [0, 0.125, 0.25, 0.375, 0.475, 0.575, 0.675, 0.775, 0.9];
/** Куда прокручивать при клике по шкале — момент, когда сцена уже собрана. */
export const CORE_KEYFRAMES = CORE_STARTS.map((s, i) => (i === CORE_STARTS.length - 1 ? 1 : s + ((CORE_STARTS[i + 1] ?? 1) - s) * 0.55));
export const CHAPTER2_AT = CORE_STARTS[3];

export const sm = (a: number, b: number, x: number) => {
  const t = Math.max(0, Math.min(1, (x - a) / (b - a)));
  return t * t * (3 - 2 * t);
};
/** Окно видимости [a, b] с мягкими краями. */
export const win = (p: number, a: number, b: number, e = 0.015) => (a <= 0 ? 1 : sm(a - e, a + e, p)) * (b >= 1 ? 1 : 1 - sm(b - e, b + e, p));

/** Смена масштаба рассказа: модель компании уступает место модели конкретного объекта. */
export const chapterReset = (p: number) => sm(0.355, 0.39, p);

// Слои-кольца появляются в первой главе (возможности среды) и остаются до конца.
const RING_AT = [0.005, 0.135, 0.155, 0.175, 0.26, 0.28];
// Во второй главе слои наполняются данными конкретного объекта.
const FILL_CH2 = [0.385, 0.48, 0.5, 0.58, 0.68, 0.78];

/** Короткая метка «+ слой» в момент, когда слой наполняется данными объекта. */
export const layerPop = (i: number, p: number) => win(p, FILL_CH2[i] + 0.012, FILL_CH2[i] + 0.075, 0.01);

export function layerAmount(i: number, p: number) {
  return sm(RING_AT[i], RING_AT[i] + 0.05, p);
}

export function layerFill(i: number, p: number) {
  const ch1 = 0.6 * sm(RING_AT[i], RING_AT[i] + 0.08, p) * (1 - 0.85 * chapterReset(p));
  const ch2 = sm(FILL_CH2[i], FILL_CH2[i] + 0.1, p);
  return Math.max(0.1, ch1, ch2);
}

