const sm = (a: number, b: number, x: number) => {
  const t = Math.max(0, Math.min(1, (x - a) / (b - a)));
  return t * t * (3 - 2 * t);
};

/** Насколько слой проявлен (0→1). ППР начинает формироваться на mockup и насыщается на площадке. */
export function layerAmount(i: number, p: number) {
  switch (i) {
    case 0:
      return 1;
    case 1:
      return sm(0.13, 0.2, p);
    case 2:
      return sm(0.27, 0.34, p);
    case 3:
      return sm(0.41, 0.48, p);
    case 4:
      return sm(0.55, 0.62, p);
    default:
      return 0.45 * sm(0.29, 0.36, p) + 0.55 * sm(0.69, 0.76, p);
  }
}

/** Насколько слой наполнен данными — растёт дольше, чем проявляется. */
export function layerFill(i: number, p: number) {
  const starts = [0, 0.13, 0.27, 0.41, 0.55, 0.29];
  return Math.max(0.12, sm(starts[i], starts[i] + 0.32, p));
}

