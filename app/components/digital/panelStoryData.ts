/** Начало каждой сцены на шкале прокрутки (0→1). */
export const STEP_STARTS = [0, 0.14, 0.36, 0.57, 0.79];

/** Ключевой кадр каждой сцены — для навигации и режима без анимации. */
export const STEP_KEYFRAMES = [0.1, 0.33, 0.53, 0.76, 1];

export function stepAt(p: number) {
  let s = 0;
  for (let i = 0; i < STEP_STARTS.length; i++) if (p >= STEP_STARTS[i]) s = i;
  return s;
}

