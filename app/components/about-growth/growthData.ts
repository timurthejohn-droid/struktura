/** Для каждого года: какие компетенции появились впервые и сколько накоплено к этому году. */
export const growthStats = (() => {
  const seen = new Set<string>();
  return growthYears.map((y) => {
    const fresh = y.competences.filter((c) => !seen.has(c));
    fresh.forEach((c) => seen.add(c));
    return { fresh: new Set(fresh), total: seen.size };
  });
})();
